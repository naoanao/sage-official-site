def section_misc() -> dict:
    h("STEP 8 — Other integrations (all optional)")
    make = ask("Make.com Webhook URL (for Stripe → Telegram/Notion alerts)")
    gumroad = ask("GUMROAD_ACCESS_TOKEN", secret=True)
    return {"GUMROAD_ACCESS_TOKEN": gumroad, "MAKE_WEBHOOK_URL": make}


# ── Section: Identity ─────────────────────────────────────────────────────────
def section_identity():
    """Set up the AI content identity (tone, niche, audience)."""
    h("STEP 9 — Your Sage AI Identity")
    p("This controls the tone and niche of all generated content.")
    tip("You can edit backend/config/identity.json any time to change this.")

    role     = ask("Your AI's role/title",          default="AI monetization expert")
    niche    = ask("Your niche (content focus)",     default="AI-powered side income and automation for solopreneurs")
    tone     = ask("Content tone",                   default="professional yet approachable")
    brand    = ask("Brand name",                     default="Sage AI")
    audience = ask("Target audience",                default="English-speaking solopreneurs who want passive income with AI tools")

    identity = {
        "role": role,
        "niche": niche,
        "tone": tone,
        "visual_style": "clean minimalist tech aesthetic",
        "language": "en",
        "brand_name": brand,
        "target_audience": audience,
    }

    identity_path = Path(__file__).parent / "backend" / "config" / "identity.json"
    import json
    with open(identity_path, "w", encoding="utf-8") as f:
        json.dump(identity, f, ensure_ascii=False, indent=2)
    ok(f"Saved identity.json: {identity_path}")
    return identity


