# ── Colour output ─────────────────────────────────────────────────────────────
GREEN  = "\033[92m"
YELLOW = "\033[93m"
CYAN   = "\033[96m"
RED    = "\033[91m"
BOLD   = "\033[1m"
RESET  = "\033[0m"

def p(text, color=RESET):   print(f"{color}{text}{RESET}")
def h(text):                print(f"\n{BOLD}{CYAN}{'='*60}\n  {text}\n{'='*60}{RESET}")
def ok(text):               print(f"{GREEN}✅ {text}{RESET}")
def warn(text):             print(f"{YELLOW}⚠️  {text}{RESET}")
def tip(text):              print(f"{CYAN}💡 {text}{RESET}")

def ask(prompt, default="", secret=False):
    """Prompt for input. Press Enter to use the default."""
    import getpass
    display = f"{CYAN}{prompt}{RESET}"
    if default:
        display += f" [{YELLOW}{default}{RESET}]"
    display += ": "
    if secret:
        val = getpass.getpass(display)
    else:
        val = input(display)
    return val.strip() or default

def ask_yn(prompt, default=True):
    suffix = " [Y/n]: " if default else " [y/N]: "
    val = input(f"{CYAN}{prompt}{RESET}{suffix}").strip().lower()
    if not val:
        return default
    return val in ("y", "yes")

def check_python_version():
    if sys.version_info < (3, 9):
        p(f"❌  Python 3.9+ is required. You are running Python {sys.version}", RED)
        p("    Download from: https://www.python.org/downloads/", RED)
        sys.exit(1)

