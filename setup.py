# ── Section: Core AI ──────────────────────────────────────────────────────────
def section_core() -> dict:
    h("STEP 1 — AI Provider (required)")
    tip("Groq is free and fast. Get your key at: https://console.groq.com/ → API Keys → Create API Key")
    groq = ask("GROQ_API_KEY", secret=True)
    if not groq:
        warn("GROQ_API_KEY not set. You can add it to .env later.")

    p("\nPerplexity is used for the research feature (optional).")
    tip("https://www.perplexity.ai/settings/api")
    perplexity = ask("PERPLEXITY_API_KEY (optional)", secret=True)

    return {"GROQ_API_KEY": groq, "PERPLEXITY_API_KEY": perplexity}


# ── Section: Notion ───────────────────────────────────────────────────────────
def section_notion() -> dict:
    h("STEP 2 — Notion (content database)")
    tip("https://www.notion.so/my-integrations → New integration → copy the token")
    tip("Then duplicate the Sage Content Pool template into your workspace.")
    use_notion = ask_yn("Set up Notion now?")
    if not use_notion:
        return {"NOTION_API_KEY": "", "NOTION_CONTENT_POOL_DB_ID": "",
                "NOTION_EVIDENCE_LEDGER_DB_ID": "", "SAGE_ENABLE_NOTION": "0"}

    key  = ask("NOTION_API_KEY (starts with secret_...)", secret=True)
    pool = ask("Content Pool Database ID (32 chars from the DB page URL)")
    tip("Find the ID in the URL: notion.so/[WORKSPACE]/[32-CHAR-ID]?v=...")
    ledger = ask("Evidence Ledger Database ID (optional)")
    return {
        "NOTION_API_KEY": key,
        "NOTION_CONTENT_POOL_DB_ID": pool,
        "NOTION_EVIDENCE_LEDGER_DB_ID": ledger,
        "SAGE_ENABLE_NOTION": "1" if key else "0",
    }


# ── Section: Bluesky ──────────────────────────────────────────────────────────
def section_bluesky() -> dict:
    h("STEP 3 — Bluesky (SNS auto-posting, recommended)")
    tip("Use an App Password — NOT your main login password.")
    tip("Bluesky → Settings → Privacy and Security → App Passwords → Add App Password")
    use = ask_yn("Set up Bluesky now?")
    if not use:
        return {"BLUESKY_HANDLE": "", "BLUESKY_APP_PASSWORD": "", "SAGE_ENABLE_BLUESKY": "0"}

    handle = ask("Bluesky handle (e.g. yourname.bsky.social — no @)")
    pwd    = ask("App Password (format: xxxx-xxxx-xxxx-xxxx)", secret=True)
    return {"BLUESKY_HANDLE": handle, "BLUESKY_APP_PASSWORD": pwd, "SAGE_ENABLE_BLUESKY": "1"}


# ── Section: Twitter ──────────────────────────────────────────────────────────
def section_twitter() -> dict:
    h("STEP 4 — Twitter / X (optional)")
    tip("https://developer.twitter.com/ → Your Project → Keys and Tokens")
    use = ask_yn("Set up Twitter/X?", default=False)
    if not use:
        return {k: "" for k in ["TWITTER_API_KEY", "TWITTER_API_SECRET",
                                  "TWITTER_ACCESS_TOKEN", "TWITTER_ACCESS_TOKEN_SECRET",
                                  "TWITTER_BEARER_TOKEN"]}
    return {
        "TWITTER_API_KEY":              ask("TWITTER_API_KEY", secret=True),
        "TWITTER_API_SECRET":           ask("TWITTER_API_SECRET", secret=True),
        "TWITTER_ACCESS_TOKEN":         ask("TWITTER_ACCESS_TOKEN", secret=True),
        "TWITTER_ACCESS_TOKEN_SECRET":  ask("TWITTER_ACCESS_TOKEN_SECRET", secret=True),
        "TWITTER_BEARER_TOKEN":         ask("TWITTER_BEARER_TOKEN", secret=True),
    }


