# ── Section: Cloudflare ───────────────────────────────────────────────────────
def section_cloudflare() -> dict:
    h("STEP 7 — Cloudflare (cloud deployment)")
    tip("https://dash.cloudflare.com → My Profile → API Tokens → Create Token")
    tip("Use the 'Edit Cloudflare Workers' template.")
    use = ask_yn("Set up Cloudflare now?")
    if not use:
        return {"CF_API_TOKEN": "", "CF_ACCOUNT_ID": "", "CF_PAGES_PROJECT_NAME": "sage-ai",
                "NGROK_AUTHTOKEN": "", "NGROK_STATIC_DOMAIN": "", "SITE_URL": ""}

    token   = ask("CF_API_TOKEN", secret=True)
    account = ask("CF_ACCOUNT_ID (32-char ID in your dashboard URL)")
    tip("Find it in: dash.cloudflare.com/[ACCOUNT_ID]/...")
    project = ask("Cloudflare Pages project name", default="sage-ai")
    site    = ask(f"Your Pages URL (e.g. https://{project}.pages.dev)", default=f"https://{project}.pages.dev")

    p("\nngrok lets you expose your local server externally (optional).")
    tip("https://dashboard.ngrok.com/get-started/your-authtoken")
    ngrok        = ask("NGROK_AUTHTOKEN (optional)", secret=True)
    ngrok_domain = ask("NGROK static domain (optional, e.g. yourname.ngrok-free.app)")

    return {
        "CF_API_TOKEN":           token,
        "CF_ACCOUNT_ID":          account,
        "CF_PAGES_PROJECT_NAME":  project,
        "SITE_URL":               site,
        "NGROK_AUTHTOKEN":        ngrok,
        "NGROK_STATIC_DOMAIN":    ngrok_domain,
    }


