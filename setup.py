# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    check_python_version()
    banner()

    p("This script will create a new .env file with your configuration.", YELLOW)
    env_path = Path(__file__).parent / ".env"
    if env_path.exists():
        if not ask_yn("\nExisting .env found. Overwrite it?", default=False):
            p("Setup cancelled. Your existing .env was not changed.", RED)
            sys.exit(0)
        shutil.copy(env_path, env_path.with_suffix(".env.backup"))
        ok("Backed up existing config to .env.backup")

    # Collect all config values
    config = {}
    config.update(section_core())
    config.update(section_notion())
    config.update(section_bluesky())
    config.update(section_twitter())
    config.update(section_instagram())
    config.update(section_telegram())
    config.update(section_cloudflare())
    config.update(section_misc())

    # Fixed / auto-generated values
    import secrets
    config["FLASK_PORT"]       = "8080"
    config["SAGE_ADMIN_TOKEN"] = secrets.token_hex(16)
    config["SAGE_VAULT_KEY"]   = secrets.token_hex(32)

    # Ensure all template keys have a value (even if empty)
    defaults = {
        "SITE_URL": "", "PERPLEXITY_API_KEY": "",
        "NOTION_EVIDENCE_LEDGER_DB_ID": "",
        "TWITTER_API_KEY": "", "TWITTER_API_SECRET": "",
        "TWITTER_ACCESS_TOKEN": "", "TWITTER_ACCESS_TOKEN_SECRET": "",
        "TWITTER_BEARER_TOKEN": "",
        "INSTAGRAM_ACCESS_TOKEN": "", "INSTAGRAM_ACCOUNT_ID": "",
        "TELEGRAM_BOT_TOKEN": "", "TELEGRAM_CHAT_ID": "",
        "SAGE_ENABLE_TELEGRAM": "0",
        "MAKE_WEBHOOK_URL": "", "GUMROAD_ACCESS_TOKEN": "",
        "CF_API_TOKEN": "", "CF_ACCOUNT_ID": "",
        "CF_PAGES_PROJECT_NAME": "sage-ai",
        "NGROK_AUTHTOKEN": "", "NGROK_STATIC_DOMAIN": "",
    }
    for k, v in defaults.items():
        config.setdefault(k, v)

    # Identity setup
    section_identity()

    # Write .env
    h("Saving your .env file...")
    env_content = ENV_TEMPLATE.format(**config)
    with open(env_path, "w", encoding="utf-8") as f:
        f.write(env_content)
    ok(f"Created: {env_path}")

    # Protect .gitignore
    gitignore_path = Path(__file__).parent / ".gitignore"
    if gitignore_path.exists():
        content = gitignore_path.read_text()
        if ".env" not in content:
            with open(gitignore_path, "a") as f:
                f.write("\n.env\n")
            ok("Added .env to .gitignore")
    else:
        warn("No .gitignore found. Make sure you never commit your .env file!")

    # Install Python packages
    h("STEP 10a — Install Python packages")
    if ask_yn("Install packages from backend/requirements.txt now?"):
        req_path = Path(__file__).parent / "backend" / "requirements.txt"
        if req_path.exists():
            subprocess.run([sys.executable, "-m", "pip", "install", "-r", str(req_path)],
                           check=False)
            ok("Python packages installed")
        else:
            warn(f"requirements.txt not found at: {req_path}")

    # Build frontend
    h("STEP 10b — Build the frontend")
    if ask_yn("Run  npm install && npm run build  now?"):
        proj_dir = Path(__file__).parent
        subprocess.run(["npm", "install"], cwd=proj_dir, check=False)
        subprocess.run(["npm", "run", "build"], cwd=proj_dir, check=False)
        ok("Frontend built successfully")

    # Workers instructions
    show_workers_instructions(config)

    # Done
    h("Setup complete!")
    p(f"""
Next steps:

  1. Follow the Workers deployment instructions shown above (STEP 10).

  2. Start the local dashboard:
       Windows:    .\\run_sage.ps1
       Mac/Linux:  python backend/flask_server.py

  3. Open your browser:
       http://localhost:8080

  4. Full guide with screenshots:
       Open  Sage_AI_Setup_Guide.docx  in your Sage folder.

Support: Set VITE_SUPPORT_EMAIL in your .env for your support contact.
""", GREEN)


if __name__ == "__main__":
    main()
